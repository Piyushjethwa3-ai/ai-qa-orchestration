"""
Replay mode: authored teaching fixtures instead of API calls.

Everything returned here comes from datasets/day4/replay_fixtures.json. Those
responses and judge outputs were written by hand to show the workflow. They are
not live responses, not live judge scores, and carry no timing or token usage.
They are separate from the proposed labels and are never generated by reading
the labels. Agreement shown with replay judge outputs does not validate any real
judge, and scripted differences between "runs" are not model variation.

The fixtures omit response_id (it is opaque and chosen at run time); this layer
adds the run's response_id when it serves a judge output.
"""

import json

from training_day4 import data

REPLAY_LABEL = "REPLAY - authored teaching fixtures. Not live observations."
REPLAY_NOTE = (
    "Replay demonstrates the workflow only. It cannot show live-model variability and cannot establish that a "
    "judge is reliable. Latency and token usage are unavailable in replay and are not shown as measurements."
)


class ReplayFixtures:
    def __init__(self, doc: dict | None = None):
        self.doc = doc if doc is not None else data.load_replay()

    @staticmethod
    def _judge_text(output: dict, response_id: str) -> str:
        return json.dumps({"response_id": response_id, **output}, indent=2, ensure_ascii=False)

    def fixed_judge_output(self, case_id: str, response_id: str) -> str | None:
        output = self.doc.get("judge_fixed", {}).get(case_id)
        return None if output is None else self._judge_text(output, response_id)

    def compare_entry(self, case_id: str, prompt: str):
        entry = self.doc.get("compare", {}).get(case_id, {}).get(prompt)
        return (None, None) if not entry else (entry["response"], entry["judge_output"])

    def repeat_entry(self, prompt: str, case_id: str, run_index: int):
        runs = self.doc.get("repeat", {}).get(prompt, {}).get(case_id, [])
        if run_index > len(runs):
            return None, None
        entry = runs[run_index - 1]
        return entry["response"], entry["judge_output"]

    def judge_text(self, output: dict | None, response_id: str) -> str | None:
        return None if output is None else self._judge_text(output, response_id)

    def has_repeat_prompt(self, prompt: str) -> bool:
        return prompt in self.doc.get("repeat", {})
